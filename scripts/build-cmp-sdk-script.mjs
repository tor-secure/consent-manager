/**
 * Build-time minify of the generic hosted CMP SDK.
 * Writes src/lib/sdk/generated/generic-cmp-sdk.min.ts for GET /api/sdk/script.
 * Does not run on visitor requests.
 */
import { createRequire } from "node:module";
import { spawnSync } from "node:child_process";
import fs from "node:fs";
import Module from "node:module";
import path from "node:path";
import zlib from "node:zlib";
import { fileURLToPath } from "node:url";
import { minify } from "terser";

const require = createRequire(import.meta.url);
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const outDir = path.join(root, ".tmp", "cmp-sdk-build");
const generatedDir = path.join(root, "src", "lib", "sdk", "generated");
const generatedTs = path.join(generatedDir, "generic-cmp-sdk.min.ts");
const sizesJson = path.join(generatedDir, "generic-cmp-sdk.sizes.json");

function compileSdk() {
  fs.mkdirSync(outDir, { recursive: true });
  const configPath = path.join(root, ".tmp", "tsconfig.cmp-sdk-build.json");
  fs.writeFileSync(
    configPath,
    JSON.stringify(
      {
        compilerOptions: {
          target: "ES2022",
          module: "commonjs",
          moduleResolution: "node",
          esModuleInterop: true,
          skipLibCheck: true,
          strict: false,
          noEmit: false,
          outDir,
          rootDir: path.join(root, "src"),
          baseUrl: root,
          paths: { "@/*": ["src/*"] },
        },
        files: [path.join(root, "src/lib/sdk/cmp-sdk-script.ts")],
      },
      null,
      2,
    ),
  );
  const tsc = path.join(root, "node_modules", "typescript", "bin", "tsc");
  const compiled = spawnSync(process.execPath, [tsc, "-p", configPath], {
    cwd: root,
    encoding: "utf8",
  });
  if (compiled.status !== 0) {
    throw new Error(compiled.stdout + "\n" + compiled.stderr);
  }
}

function loadBuildGeneric() {
  const original = Module._load;
  Module._load = function patched(request, parent, isMain) {
    if (request === "server-only") return {};
    if (request === "next/server") {
      return {
        NextResponse: class extends Response {
          static json(body, init) {
            return Response.json(body, init);
          }
        },
      };
    }
    if (request.startsWith("@/")) {
      const rel = request.slice(2).replace(/\.ts$/, "");
      return original.call(this, path.join(outDir, `${rel}.js`), parent, isMain);
    }
    return original.call(this, request, parent, isMain);
  };
  try {
    return require(path.join(outDir, "lib/sdk/cmp-sdk-script.js"));
  } finally {
    Module._load = original;
  }
}

function sizes(label, source) {
  const raw = Buffer.from(source, "utf8");
  return {
    label,
    bytes: raw.length,
    gzip: zlib.gzipSync(raw, { level: 9 }).length,
    brotli: zlib.brotliCompressSync(raw, {
      params: { [zlib.constants.BROTLI_PARAM_QUALITY]: 11 },
    }).length,
  };
}

function pctDelta(before, after) {
  if (!before) return null;
  return Math.round(((after - before) / before) * 1000) / 10;
}

async function main() {
  compileSdk();
  const { buildGenericCmpSdkScript } = loadBuildGeneric();
  const raw = buildGenericCmpSdkScript();
  if (!raw || typeof raw !== "string") {
    throw new Error("buildGenericCmpSdkScript() returned empty output");
  }

  const result = await minify(raw, {
    compress: true,
    mangle: true,
    // Property mangling stays disabled (do not set mangle.properties).
    format: { comments: false },
  });
  const minified = result.code || "";
  if (!minified) {
    throw new Error("Terser produced empty output");
  }
  if (minified.length >= raw.length) {
    throw new Error(
      `Minified SDK (${minified.length}) is not smaller than raw (${raw.length})`,
    );
  }

  const before = sizes("unminified", raw);
  const after = sizes("minified", minified);
  const report = {
    generatedAt: new Date().toISOString(),
    before,
    after,
    delta: {
      bytes: after.bytes - before.bytes,
      gzip: after.gzip - before.gzip,
      brotli: after.brotli - before.brotli,
      bytesPct: pctDelta(before.bytes, after.bytes),
      gzipPct: pctDelta(before.gzip, after.gzip),
      brotliPct: pctDelta(before.brotli, after.brotli),
    },
  };

  fs.mkdirSync(generatedDir, { recursive: true });
  const ts = `/* AUTO-GENERATED by scripts/build-cmp-sdk-script.mjs — do not edit. */
/* eslint-disable */
export const GENERIC_CMP_SDK_SCRIPT_MINIFIED = ${JSON.stringify(minified)};
`;
  fs.writeFileSync(generatedTs, ts, "utf8");
  fs.writeFileSync(sizesJson, JSON.stringify(report, null, 2), "utf8");

  console.log(
    `[build:cmp-sdk] raw ${before.bytes} B / gzip ${before.gzip} B / br ${before.brotli} B`,
  );
  console.log(
    `[build:cmp-sdk] min ${after.bytes} B / gzip ${after.gzip} B / br ${after.brotli} B (${report.delta.gzipPct}% gzip)`,
  );
  console.log(`[build:cmp-sdk] wrote ${path.relative(root, generatedTs)}`);
}

main().catch((error) => {
  console.error("[build:cmp-sdk] failed:", error);
  process.exit(1);
});
